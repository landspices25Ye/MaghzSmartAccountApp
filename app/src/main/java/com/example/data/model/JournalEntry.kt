package com.example.data.model

import androidx.room.Entity
import androidx.room.PrimaryKey

enum class AccountCategory(val titleAr: String, val isNormalDebit: Boolean) {
    ASSET("أصول", true),
    LIABILITY("خصوم والتزامات", false),
    EQUITY("حقوق ملكية ورأس مال", false),
    REVENUE("إيرادات ومبيعات", false),
    EXPENSE("مصروفات تشغيلية", true)
}

@Entity(tableName = "journal_entries")
data class JournalEntry(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val entryNumber: String,
    val timestamp: Long = System.currentTimeMillis(),
    val description: String,
    val sourceTransactionId: Long? = null,
    val isAutoGenerated: Boolean = true,
    val currency: String = "ر.س"
)

@Entity(tableName = "journal_line_items")
data class JournalLineItem(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val journalEntryId: Long,
    val accountCategory: AccountCategory,
    val accountName: String,
    val debit: Double = 0.0,
    val credit: Double = 0.0,
    val notes: String = ""
)

data class JournalEntryWithLines(
    val entry: JournalEntry,
    val lines: List<JournalLineItem>
) {
    val totalDebit: Double get() = lines.sumOf { it.debit }
    val totalCredit: Double get() = lines.sumOf { it.credit }
    val isBalanced: Boolean get() = Math.abs(totalDebit - totalCredit) < 0.001
}

data class TrialBalanceRow(
    val accountName: String,
    val category: AccountCategory,
    val totalDebit: Double,
    val totalCredit: Double,
    val netDebit: Double,
    val netCredit: Double
)

data class FinancialStatementSummary(
    val totalAssets: Double,
    val totalLiabilities: Double,
    val totalEquity: Double,
    val totalRevenue: Double,
    val totalExpenses: Double,
    val netProfit: Double,
    val workingCapital: Double,
    val liquidityRatio: Double
)
