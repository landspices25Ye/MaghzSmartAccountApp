import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object DoubleEntryEngine {

    private val entryDateFormat = SimpleDateFormat("yyyyMMdd-HHmmss", Locale.ENGLISH)

    /**
     * Converts a single operational transaction into a balanced double-entry voucher
     * where sum(Debit) == sum(Credit).
     */
    fun createJournalEntryForTransaction(
        transaction: TransactionRecord,
        cashBoxName: String = "الصندوق الرئيسي",
        targetCashBoxName: String? = null,
        partyName: String? = null,
        partyType: PartyType? = null,
        currencySymbol: String = "ر.س"
    ): Pair<JournalEntry, List<JournalLineItem>> {
        val entryNumber = "JV-${entryDateFormat.format(Date(transaction.timestamp))}-${transaction.id}"
        val desc = transaction.description.ifBlank { transaction.type.titleAr }

        val journalEntry = JournalEntry(
            entryNumber = entryNumber,
            timestamp = transaction.timestamp,
            description = desc,
            sourceTransactionId = transaction.id,
            isAutoGenerated = true,
            currency = transaction.currency.ifBlank { currencySymbol }
        )

        val lines = mutableListOf<JournalLineItem>()
        val amount = transaction.amount

        when (transaction.type) {
            TransactionType.CUSTOMER_RECEIPT -> {
                val customerName = partyName ?: "حساب العميل"
                // Dr: Cash (Asset +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "صندوق: $cashBoxName",
                        debit = amount,
                        credit = 0.0,
                        notes = "قبض نقدي من $customerName"
                    )
                )
                // Cr: Accounts Receivable (Asset -)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "ذمم مدينة: $customerName",
                        debit = 0.0,
                        credit = amount,
                        notes = "سداد دفعة من العميل"
                    )
                )
            }

            TransactionType.SUPPLIER_PAYMENT -> {
                val supplierName = partyName ?: "حساب المورد"
                // Dr: Accounts Payable (Liability -)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.LIABILITY,
                        accountName = "ذمم دائنة: $supplierName",
                        debit = amount,
                        credit = 0.0,
                        notes = "سداد مستحقات المورد"
                    )
                )
                // Cr: Cash (Asset -)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "صندوق: $cashBoxName",
                        debit = 0.0,
                        credit = amount,
                        notes = "دفع نقدي للمورد $supplierName"
                    )
                )
            }

            TransactionType.CUSTOMER_NEW_DEBIT -> {
                val customerName = partyName ?: "حساب العميل"
                // Dr: Accounts Receivable (Asset +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "ذمم مدينة: $customerName",
                        debit = amount,
                        credit = 0.0,
                        notes = "تسجيل دين/مبيعات آجلة على العميل"
                    )
                )
                // Cr: Sales / Revenue (Revenue +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.REVENUE,
                        accountName = "إيرادات ومبيعات آجلة",
                        debit = 0.0,
                        credit = amount,
                        notes = "مبيعات للعميل $customerName"
                    )
                )
            }

            TransactionType.SUPPLIER_NEW_CREDIT -> {
                val supplierName = partyName ?: "حساب المورد"
                // Dr: Purchases / Cost of Goods (Expense +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.EXPENSE,
                        accountName = "مشتريات وبضاعة آجلة",
                        debit = amount,
                        credit = 0.0,
                        notes = "مشتريات بالآجل من المورد $supplierName"
                    )
                )
                // Cr: Accounts Payable (Liability +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.LIABILITY,
                        accountName = "ذمم دائنة: $supplierName",
                        debit = 0.0,
                        credit = amount,
                        notes = "استحقاق للمورد"
                    )
                )
            }

            TransactionType.EXPENSE -> {
                val categoryName = transaction.category.ifBlank { "مصروفات عامة" }
                // Dr: Expense (Expense +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.EXPENSE,
                        accountName = "مصروف: $categoryName",
                        debit = amount,
                        credit = 0.0,
                        notes = desc
                    )
                )
                // Cr: Cash (Asset -)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "صندوق: $cashBoxName",
                        debit = 0.0,
                        credit = amount,
                        notes = "صرف نقدي لـ $categoryName"
                    )
                )
            }

            TransactionType.INCOME -> {
                // Dr: Cash (Asset +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "صندوق: $cashBoxName",
                        debit = amount,
                        credit = 0.0,
                        notes = "قبض إيراد نقدي"
                    )
                )
                // Cr: Revenue (Revenue +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.REVENUE,
                        accountName = "إيرادات نقدية متنوعة",
                        debit = 0.0,
                        credit = amount,
                        notes = desc
                    )
                )
            }

            TransactionType.TRANSFER -> {
                val target = targetCashBoxName ?: "الصندوق المحول إليه"
                // Dr: Target Cash (Asset +)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "صندوق: $target",
                        debit = amount,
                        credit = 0.0,
                        notes = "تحويل وارد من $cashBoxName"
                    )
                )
                // Cr: Source Cash (Asset -)
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.ASSET,
                        accountName = "صندوق: $cashBoxName",
                        debit = 0.0,
                        credit = amount,
                        notes = "تحويل صادر إلى $target"
                    )
                )
            }

            TransactionType.SETTLEMENT -> {
                val targetName = partyName ?: cashBoxName
                // Dr/Cr adjustment to Equity
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = AccountCategory.EQUITY,
                        accountName = "تسويات وفروقات أرصدة",
                        debit = if (amount >= 0) amount else 0.0,
                        credit = if (amount < 0) -amount else 0.0,
                        notes = "تسوية حساب $targetName"
                    )
                )
                lines.add(
                    JournalLineItem(
                        journalEntryId = 0,
                        accountCategory = if (partyType == PartyType.SUPPLIER) AccountCategory.LIABILITY else AccountCategory.ASSET,
                        accountName = if (partyName != null) "طرف: $partyName" else "صندوق: $cashBoxName",
                        debit = if (amount < 0) -amount else 0.0,
                        credit = if (amount >= 0) amount else 0.0,
                        notes = desc
                    )
                )
            }
        }

        return Pair(journalEntry, lines)
    }

    /**
     * Builds the standard Trial Balance (ميزان المراجعة) by grouping all line items
     * across all accounts.
     */
    fun computeTrialBalance(allLines: List<JournalLineItem>): List<TrialBalanceRow> {
        val grouped = allLines.groupBy { it.accountName }
        return grouped.map { (accountName, lines) ->
            val totalDebit = lines.sumOf { it.debit }
            val totalCredit = lines.sumOf { it.credit }
            val category = lines.firstOrNull()?.accountCategory ?: AccountCategory.ASSET
            val net = totalDebit - totalCredit
            TrialBalanceRow(
                accountName = accountName,
                category = category,
                totalDebit = totalDebit,
                totalCredit = totalCredit,
                netDebit = if (net > 0) net else 0.0,
                netCredit = if (net < 0) -net else 0.0
            )
        }.sortedWith(compareBy({ it.category.ordinal }, { it.accountName }))
    }

    /**
     * Computes the complete Executive Financial Statement (P&L, Balance Sheet, Liquidity)
     */
    fun computeFinancialSummary(allLines: List<JournalLineItem>): FinancialStatementSummary {
        var totalAssets = 0.0
        var totalLiabilities = 0.0
        var totalEquity = 0.0
        var totalRevenue = 0.0
        var totalExpenses = 0.0

        val trialBalance = computeTrialBalance(allLines)
        for (row in trialBalance) {
            when (row.category) {
                AccountCategory.ASSET -> {
                    totalAssets += (row.totalDebit - row.totalCredit)
                }
                AccountCategory.LIABILITY -> {
                    totalLiabilities += (row.totalCredit - row.totalDebit)
                }
                AccountCategory.EQUITY -> {
                    totalEquity += (row.totalCredit - row.totalDebit)
                }
                AccountCategory.REVENUE -> {
                    totalRevenue += (row.totalCredit - row.totalDebit)
                }
                AccountCategory.EXPENSE -> {
                    totalExpenses += (row.totalDebit - row.totalCredit)
                }
            }
        }

        val netProfit = totalRevenue - totalExpenses
        // Balance sheet equality: Assets = Liabilities + (Equity + NetProfit)
        val workingCapital = totalAssets - totalLiabilities
        val liquidityRatio = if (totalLiabilities > 0.0) totalAssets / totalLiabilities else if (totalAssets > 0.0) 99.9 else 1.0

        return FinancialStatementSummary(
            totalAssets = if (totalAssets > 0) totalAssets else 0.0,
            totalLiabilities = if (totalLiabilities > 0) totalLiabilities else 0.0,
            totalEquity = totalEquity,
            totalRevenue = totalRevenue,
            totalExpenses = totalExpenses,
            netProfit = netProfit,
            workingCapital = workingCapital,
            liquidityRatio = liquidityRatio
        )
    }
}
